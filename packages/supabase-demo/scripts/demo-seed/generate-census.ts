/**
 * Demo census generator — emits seed/20_demo_census.sql.
 *
 * The cast of the demo clinic: seed staff, 20 fictional patients (longitudinal
 * charts, today's OPD board with one patient per workflow bucket, a month of
 * paid + HMIS-coded history, one active admission), pharmacy stock with FEFO
 * batches. Scenarios are drawn from the KaribuLearn canonical cases
 * (content/learn/generated/hc3-core-draft-v0.1.0); chart-level data is curated
 * against the real catalogs (scripts/demo-seed/catalogs.json).
 *
 * Rules (docs/demo-environment-plan.md §4):
 *   - fixed UUIDs, ON CONFLICT DO NOTHING → idempotent
 *   - ALL dates relative to kampala_today()/NOW() — reseeding is always "today"
 *   - every worklist bucket is targeted via the exact RPC predicates
 *     (rpc_get_opd_patients_today, rpc_worklist_* — see baseline schema)
 *   - zero real PHI: every person is invented
 *
 * Run: pnpm --filter @karibu/supabase-demo generate-census
 */

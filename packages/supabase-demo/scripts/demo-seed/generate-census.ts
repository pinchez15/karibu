const med = (code: string) => {
  const m = catalogs.medications.find((x) => x.code === code)
  if (!m) throw new Error(`unknown medication code ${code}`)
  return m
}
const lab = (code: string) => {
  const l = catalogs.lab_tests.find((x) => x.code === code)
  if (!l) throw new Error(`unknown lab code ${code}`)
  return l
}

